// ===== 当前语言 =====
let currentLang = localStorage.getItem("portfolio-lang") || "zh";

// ===== 应用语言 =====
function applyLanguage(lang) {
    currentLang = lang;
    localStorage.setItem("portfolio-lang", lang);

    // 更新切换按钮状态
    document.querySelectorAll(".lang-toggle button").forEach(btn => {
        btn.classList.toggle("active", btn.dataset.lang === lang);
    });

    // 更新所有带 data-i18n 属性的元素
    document.querySelectorAll("[data-i18n]").forEach(el => {
        const key = el.getAttribute("data-i18n");
        if (i18n[lang] && i18n[lang][key]) {
            el.innerHTML = i18n[lang][key];
        }
    });

    // 更新 html lang 属性
    document.documentElement.lang = lang === "zh" ? "zh-CN" : "en";
}

// ===== 初始化 GitHub 链接 =====
function initGitHubLinks() {
    document.querySelectorAll("[data-release]").forEach(el => {
        const repo = REPO_MAP[el.getAttribute("data-release")];
        el.href = `https://github.com/${GITHUB_USER}/${repo}/releases/latest`;
    });
}

// ===== 事件绑定 =====
document.querySelectorAll(".lang-toggle button").forEach(btn => {
    btn.addEventListener("click", () => applyLanguage(btn.dataset.lang));
});

// ===== 工具卡片点击跳转详情页 =====
document.querySelectorAll("[data-detail]").forEach(card => {
    card.addEventListener("click", e => {
        if (e.target.closest("a, button")) return; // 点击按钮/链接时不跳转
        window.location.href = card.getAttribute("data-detail");
    });
});

// ===== 初始化 =====
applyLanguage(currentLang);
initGitHubLinks();
